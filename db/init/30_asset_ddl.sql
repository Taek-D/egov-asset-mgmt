-- 초기화 클라이언트가 파일을 latin1로 읽어 한글이 이중 인코딩되는 것을 막는다(서버 collation 설정 아님)
SET NAMES utf8mb4;

-- 기관 비품·자산 관리 업무 테이블 (MySQL 8.0)
-- 코드값: 품목 유형 QTY/UNIT, 자산 상태 STORED/IN_USE/REPAIR/DISPOSED,
--         신청 상태 PENDING/REJECTED/APPROVED/DELIVERED/CANCELED/DELIVERY_CANCELED,
--         품목 결과 PENDING/APPROVED/REJECTED, 재고 변동 IN/ADJUST/RESERVE/RELEASE/DELIVER

-- 품목. 수량 비품은 STOCK_QTY, 개별 자산은 RESERVED_QTY(확보 수량)를 쓴다
CREATE TABLE ASSET_ITEM
(
	ITEM_CODE             CHAR(20) NOT NULL,
	ITEM_NM               VARCHAR(100) NOT NULL,
	ITEM_TY               VARCHAR(4) NOT NULL,
	CL_CODE               VARCHAR(15) NULL,
	UNIT_CODE             VARCHAR(15) NULL,
	MIN_QTY               INT NOT NULL DEFAULT 0,
	USE_AT                CHAR(1) NOT NULL DEFAULT 'Y',
	STOCK_QTY             INT NOT NULL DEFAULT 0,
	RESERVED_QTY          INT NOT NULL DEFAULT 0,
	-- 사용 중 품목끼리만 이름이 유일하도록 하는 보조 열(사용 중지면 NULL)
	ACTIVE_ITEM_NM        VARCHAR(100) GENERATED ALWAYS AS (CASE WHEN USE_AT = 'Y' THEN ITEM_NM END) STORED,
	FRST_REGISTER_ID      VARCHAR(20) NOT NULL,
	FRST_REGIST_PNTTM     DATETIME NOT NULL,
	LAST_UPDUSR_ID        VARCHAR(20) NULL,
	LAST_UPDT_PNTTM       DATETIME NULL,
	PRIMARY KEY (ITEM_CODE),
	UNIQUE KEY ASSET_ITEM_UK_ACTIVE_NM (ACTIVE_ITEM_NM),
	CONSTRAINT ASSET_ITEM_CK_TY CHECK (ITEM_TY IN ('QTY', 'UNIT')),
	CONSTRAINT ASSET_ITEM_CK_USE CHECK (USE_AT IN ('Y', 'N')),
	CONSTRAINT ASSET_ITEM_CK_MIN CHECK (MIN_QTY >= 0),
	CONSTRAINT ASSET_ITEM_CK_STOCK CHECK (STOCK_QTY >= 0),
	CONSTRAINT ASSET_ITEM_CK_RESERVED CHECK (RESERVED_QTY >= 0)
);

-- 재고 변동 이력. 수량 비품 행은 재고 수량 기준, 개별 자산 행은 가용 기준
CREATE TABLE ASSET_STOCK_HIST
(
	STOCK_HIST_ID         CHAR(20) NOT NULL,
	ITEM_CODE             CHAR(20) NOT NULL,
	HIST_TY               VARCHAR(10) NOT NULL,
	CHANGE_QTY            INT NOT NULL,
	AFTER_QTY             INT NOT NULL,
	RESN                  VARCHAR(500) NULL,
	REQ_NO                CHAR(20) NULL,
	PROCESS_ID            VARCHAR(20) NOT NULL,
	PROCESS_PNTTM         DATETIME NOT NULL,
	PRIMARY KEY (STOCK_HIST_ID),
	KEY ASSET_STOCK_HIST_IX_ITEM (ITEM_CODE),
	CONSTRAINT ASSET_STOCK_HIST_FK_ITEM FOREIGN KEY (ITEM_CODE) REFERENCES ASSET_ITEM (ITEM_CODE),
	CONSTRAINT ASSET_STOCK_HIST_CK_TY CHECK (HIST_TY IN ('IN', 'ADJUST', 'RESERVE', 'RELEASE', 'DELIVER'))
);

-- 개별 자산. 자산번호는 폐기된 자산을 포함해 전체에서 유일
CREATE TABLE ASSET_UNIT
(
	ASSET_NO              VARCHAR(50) NOT NULL,
	ITEM_CODE             CHAR(20) NOT NULL,
	STTUS                 VARCHAR(10) NOT NULL,
	USER_ID               VARCHAR(20) NULL,
	RM                    VARCHAR(500) NULL,
	FRST_REGISTER_ID      VARCHAR(20) NOT NULL,
	FRST_REGIST_PNTTM     DATETIME NOT NULL,
	LAST_UPDUSR_ID        VARCHAR(20) NULL,
	LAST_UPDT_PNTTM       DATETIME NULL,
	PRIMARY KEY (ASSET_NO),
	KEY ASSET_UNIT_IX_ITEM (ITEM_CODE, STTUS),
	CONSTRAINT ASSET_UNIT_FK_ITEM FOREIGN KEY (ITEM_CODE) REFERENCES ASSET_ITEM (ITEM_CODE),
	CONSTRAINT ASSET_UNIT_CK_STTUS CHECK (STTUS IN ('STORED', 'IN_USE', 'REPAIR', 'DISPOSED'))
);

-- 개별 자산 상태 이력. 등록 시 첫 행은 BEFORE_STTUS가 NULL
CREATE TABLE ASSET_UNIT_HIST
(
	UNIT_HIST_ID          CHAR(20) NOT NULL,
	ASSET_NO              VARCHAR(50) NOT NULL,
	BEFORE_STTUS          VARCHAR(10) NULL,
	AFTER_STTUS           VARCHAR(10) NOT NULL,
	RESN                  VARCHAR(500) NULL,
	REQ_NO                CHAR(20) NULL,
	PROCESS_ID            VARCHAR(20) NOT NULL,
	PROCESS_PNTTM         DATETIME NOT NULL,
	PRIMARY KEY (UNIT_HIST_ID),
	KEY ASSET_UNIT_HIST_IX_ASSET (ASSET_NO),
	CONSTRAINT ASSET_UNIT_HIST_FK_ASSET FOREIGN KEY (ASSET_NO) REFERENCES ASSET_UNIT (ASSET_NO)
);

-- 신청서 헤더. ORGNZT_ID는 신청 당시 부서(이후 바뀌지 않음)
CREATE TABLE ASSET_REQ
(
	REQ_NO                CHAR(20) NOT NULL,
	APPLCNT_ID            VARCHAR(20) NOT NULL,
	ORGNZT_ID             CHAR(20) NOT NULL,
	REQ_RESN              VARCHAR(1000) NULL,
	STTUS                 VARCHAR(20) NOT NULL,
	REQ_PNTTM             DATETIME NOT NULL,
	APRV_ID               VARCHAR(20) NULL,
	APRV_PNTTM            DATETIME NULL,
	LAST_PROCESS_ID       VARCHAR(20) NULL,
	LAST_PROCESS_PNTTM    DATETIME NULL,
	PRIMARY KEY (REQ_NO),
	KEY ASSET_REQ_IX_APPLCNT (APPLCNT_ID),
	KEY ASSET_REQ_IX_ORGNZT (ORGNZT_ID, STTUS),
	CONSTRAINT ASSET_REQ_CK_STTUS CHECK (STTUS IN ('PENDING', 'REJECTED', 'APPROVED', 'DELIVERED', 'CANCELED', 'DELIVERY_CANCELED'))
);

-- 신청 품목. 같은 품목은 한 줄로 합치므로 (신청번호, 품목)이 유일
CREATE TABLE ASSET_REQ_LINE
(
	REQ_NO                CHAR(20) NOT NULL,
	ITEM_CODE             CHAR(20) NOT NULL,
	REQ_QTY               INT NOT NULL,
	APRV_QTY              INT NULL,
	LINE_STTUS            VARCHAR(10) NOT NULL DEFAULT 'PENDING',
	REJECT_RESN           VARCHAR(500) NULL,
	PRIMARY KEY (REQ_NO, ITEM_CODE),
	KEY ASSET_REQ_LINE_IX_ITEM (ITEM_CODE),
	CONSTRAINT ASSET_REQ_LINE_FK_REQ FOREIGN KEY (REQ_NO) REFERENCES ASSET_REQ (REQ_NO),
	CONSTRAINT ASSET_REQ_LINE_FK_ITEM FOREIGN KEY (ITEM_CODE) REFERENCES ASSET_ITEM (ITEM_CODE),
	CONSTRAINT ASSET_REQ_LINE_CK_QTY CHECK (REQ_QTY >= 1),
	CONSTRAINT ASSET_REQ_LINE_CK_APRV CHECK (APRV_QTY IS NULL OR (APRV_QTY >= 1 AND APRV_QTY <= REQ_QTY)),
	CONSTRAINT ASSET_REQ_LINE_CK_STTUS CHECK (LINE_STTUS IN ('PENDING', 'APPROVED', 'REJECTED'))
);

-- 신청서 처리 이력. 제출 시 첫 행은 BEFORE_STTUS가 NULL
CREATE TABLE ASSET_REQ_HIST
(
	REQ_HIST_ID           CHAR(20) NOT NULL,
	REQ_NO                CHAR(20) NOT NULL,
	BEFORE_STTUS          VARCHAR(20) NULL,
	AFTER_STTUS           VARCHAR(20) NOT NULL,
	RESN                  VARCHAR(500) NULL,
	PROCESS_ID            VARCHAR(20) NOT NULL,
	PROCESS_PNTTM         DATETIME NOT NULL,
	PRIMARY KEY (REQ_HIST_ID),
	KEY ASSET_REQ_HIST_IX_REQ (REQ_NO),
	CONSTRAINT ASSET_REQ_HIST_FK_REQ FOREIGN KEY (REQ_NO) REFERENCES ASSET_REQ (REQ_NO)
);

-- 부서장 지정. 부서당 최대 1명(부서가 기본키)
CREATE TABLE ASSET_DEPT_HEAD
(
	ORGNZT_ID             CHAR(20) NOT NULL,
	EMPLYR_ID             VARCHAR(20) NOT NULL,
	ASSIGN_ID             VARCHAR(20) NOT NULL,
	ASSIGN_PNTTM          DATETIME NOT NULL,
	PRIMARY KEY (ORGNZT_ID)
);

-- 재고 부족 집계 실행(결과가 0건인 실행도 남긴다)
CREATE TABLE ASSET_SHORTAGE_RUN
(
	RUN_ID                CHAR(20) NOT NULL,
	RUN_TY                VARCHAR(10) NOT NULL,
	RUN_PNTTM             DATETIME NOT NULL,
	ITEM_CNT              INT NOT NULL DEFAULT 0,
	RUN_USER_ID           VARCHAR(20) NULL,
	PRIMARY KEY (RUN_ID),
	CONSTRAINT ASSET_SHORTAGE_RUN_CK_TY CHECK (RUN_TY IN ('AUTO', 'MANUAL'))
);

-- 재고 부족 집계 결과(실행별 품목)
CREATE TABLE ASSET_SHORTAGE
(
	RUN_ID                CHAR(20) NOT NULL,
	ITEM_CODE             CHAR(20) NOT NULL,
	AVAIL_QTY             INT NOT NULL,
	MIN_QTY               INT NOT NULL,
	SHORT_QTY             INT NOT NULL,
	PRIMARY KEY (RUN_ID, ITEM_CODE),
	CONSTRAINT ASSET_SHORTAGE_FK_RUN FOREIGN KEY (RUN_ID) REFERENCES ASSET_SHORTAGE_RUN (RUN_ID)
);

-- 초기화 작업 적용 기록(데모 암호 1회 적용 등)
CREATE TABLE ASSET_SETUP
(
	SETUP_KEY             VARCHAR(50) NOT NULL,
	APPLIED_PNTTM         DATETIME NOT NULL,
	PRIMARY KEY (SETUP_KEY)
);
